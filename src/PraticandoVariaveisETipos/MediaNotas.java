package PraticandoVariaveisETipos;

public class MediaNotas {
    public static void main(String[] args) {
        double nota1 = 7.5;
        double nota2 = 8.0;
        double nota3 = 9.0;

        double calcularMedia = (nota1 + nota2 + nota3) / 3;

        System.out.println("A média das notas é: " + calcularMedia);
    }
}
